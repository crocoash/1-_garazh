# Объединение конфигурации базы с файлом .cf в пакетном режиме.
# Запускать НА МАШИНЕ С 1С.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File _tools\merge-cf.ps1
#
# Что делает по шагам:
#   1. выгружает ТЕКУЩУЮ конфигурацию базы в резервный .cf (точка отката);
#   2. Конфигуратор: /MergeCfg <файл> -Settings <настройки> — объединение;
#   3. по ключу -ПрименитьКБазе: /UpdateDBCfg. По умолчанию НЕ применяет —
#      результат объединения сначала смотрят глазами в Конфигураторе.
#
# ГЛАВНОЕ ПРО НАСТРОЙКИ. Объединение — это набор решений «чей объект берём».
# Пакетный режим сам их не принимает, он читает их из файла настроек. Файл
# готовится один раз руками:
#   Конфигуратор → Конфигурация → Сравнить, объединить с конфигурацией из файла…
#   → расставить флажки → «Действия» → «Сохранить настройки объединения в файл…»
# Сохранить как _tools\merge-settings.txt — скрипт подхватит его сам.
# Расширение .txt, а не .xml, намеренно: «Загрузить конфигурацию из файлов» парсит
# КАЖДЫЙ .xml в дереве выгрузки и спотыкается о посторонние (уже ловили на эталоне
# штрихкода). Внутри файл всё равно остаётся XML — платформе расширение безразлично.
# Без файла настроек объединение идёт по умолчанию платформы: молча возьмёт
# не ту сторону. Поэтому без него скрипт останавливается (обойти: -БезНастроек).
#
# Ключи:
#   -Файл <путь.cf>        что объединяем (по умолчанию garazh-cp.cf с Рабочего стола)
#   -Настройки <путь>      файл настроек объединения
#   -ПрименитьКБазе        после объединения обновить конфигурацию базы данных
#   -БезРезервнойКопии     не выгружать точку отката (быстрее, но откатывать нечем)
#   -БезНастроек           объединять по умолчанию платформы, осознанно
#   -Принудительно         добавить ключ -force (продолжать при предупреждениях)

param(
    [string]$Файл = "",
    [string]$Настройки = "",
    [switch]$ПрименитьКБазе,
    [switch]$БезРезервнойКопии,
    [switch]$БезНастроек,
    [switch]$Принудительно
)

# ==============================================================================
#  НАСТРОЙКИ. Пользователь, пароль и строка соединения берутся из того же
#  update-base.local.ps1, что и у update-base.ps1 — второй раз вписывать не надо.
# ==============================================================================

$Пользователь = ""
$Пароль       = ""
$База         = "/S app1\garazh-cp"
$Платформа    = ""

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

try {
    [Console]::OutputEncoding = [System.Text.Encoding]::UTF8
    $OutputEncoding = [System.Text.Encoding]::UTF8
} catch { }

$локальные = Join-Path $PSScriptRoot "update-base.local.ps1"
if (Test-Path $локальные) {
    . $локальные
    Write-Host "Настройки взяты из update-base.local.ps1" -ForegroundColor DarkGray
}

function Шаг($текст) {
    Write-Host ""
    Write-Host "== $текст" -ForegroundColor Cyan
}

function Отказ($текст) {
    Write-Host ""
    Write-Host $текст -ForegroundColor Red
    Write-Host "Объединение НЕ выполнено." -ForegroundColor Red
    exit 1
}

function ПрочитатьЛог($путь) {
    if (-not (Test-Path $путь)) { return "" }
    $текст = [System.IO.File]::ReadAllText($путь, [System.Text.Encoding]::UTF8)
    if ($текст -match "\uFFFD") {
        $текст = [System.IO.File]::ReadAllText($путь, [System.Text.Encoding]::Default)
    }
    return $текст.Trim()
}

# --- Платформа ---------------------------------------------------------------
if (-not $Платформа) {
    $кандидаты = @()
    foreach ($папка in @("$env:ProgramFiles\1cv8", "${env:ProgramFiles(x86)}\1cv8")) {
        if (Test-Path $папка) {
            $кандидаты += Get-ChildItem -Path $папка -Directory |
                Where-Object { Test-Path (Join-Path $_.FullName "bin\1cv8.exe") }
        }
    }
    if ($кандидаты.Count -eq 0) {
        Отказ "Не найден 1cv8.exe. Пропишите путь в настройке `$Платформа в начале скрипта."
    }
    $свежая = $кандидаты |
        Sort-Object { try { [version]$_.Name } catch { [version]"0.0.0.0" } } |
        Select-Object -Last 1
    $Платформа = Join-Path $свежая.FullName "bin\1cv8.exe"
}
if (-not (Test-Path $Платформа)) { Отказ "Не найден файл платформы: $Платформа" }
if (-not $Пользователь) { Отказ "Не заполнен `$Пользователь — см. _tools\update-base.local.ps1." }

# --- Что объединяем ----------------------------------------------------------
$рабочийСтол = [Environment]::GetFolderPath("Desktop")

if (-not $Файл) { $Файл = Join-Path $рабочийСтол "garazh-cp.cf" }
if (-not (Test-Path $Файл)) { Отказ "Не найден файл конфигурации: $Файл" }
$Файл = (Resolve-Path $Файл).Path

if (-not $Настройки) {
    $поумолчанию = Join-Path $PSScriptRoot "merge-settings.txt"
    if (Test-Path $поумолчанию) { $Настройки = $поумолчанию }
}

if ($Настройки) {

    if (-not (Test-Path $Настройки)) { Отказ "Не найден файл настроек объединения: $Настройки" }
    $Настройки = (Resolve-Path $Настройки).Path

} elseif (-not $БезНастроек) {

    Write-Host "НЕ НАЙДЕН ФАЙЛ НАСТРОЕК ОБЪЕДИНЕНИЯ." -ForegroundColor Red
    Write-Host ""
    Write-Host "Объединение — это решения «чей объект берём»; без настроек платформа примет" -ForegroundColor Yellow
    Write-Host "их за вас по умолчанию и может молча взять не ту сторону." -ForegroundColor Yellow
    Write-Host ""
    Write-Host "Подготовить один раз в Конфигураторе:" -ForegroundColor Yellow
    Write-Host "  Конфигурация → Сравнить, объединить с конфигурацией из файла…" -ForegroundColor Yellow
    Write-Host "  → расставить флажки → Действия → Сохранить настройки объединения в файл…" -ForegroundColor Yellow
    Write-Host "Сохранить как: $(Join-Path $PSScriptRoot 'merge-settings.txt')" -ForegroundColor Yellow
    Write-Host ""
    Write-Host "Осознанно объединить по умолчанию: ключ -БезНастроек." -ForegroundColor Yellow
    Отказ "Остановлено до объединения."
}

Write-Host "Платформа:   $Платформа" -ForegroundColor DarkGray
Write-Host "База:        $База" -ForegroundColor DarkGray
Write-Host "Объединяю с: $Файл" -ForegroundColor DarkGray
if ($Настройки) {
    Write-Host "Настройки:   $Настройки" -ForegroundColor DarkGray
} else {
    Write-Host "Настройки:   НЕТ — по умолчанию платформы (-БезНастроек)" -ForegroundColor Yellow
}

# --- Запуск Конфигуратора ----------------------------------------------------
$логи = Join-Path $env:TEMP "1c-merge-cf"
if (-not (Test-Path $логи)) { New-Item -ItemType Directory -Path $логи | Out-Null }

# Start-Process склеивает массив аргументов через пробел и ничего не экранирует:
# имя пользователя с пробелом уедет в 1С двумя аргументами.
function ВКавычки($значение) {
    if ($null -eq $значение) { return '""' }
    $строка = [string]$значение
    if ($строка -eq "" -or $строка -match '\s') { return '"' + $строка + '"' }
    return $строка
}

function ЗапуститьКонфигуратор($имяШага, $аргументы) {

    $лог = Join-Path $логи "$имяШага.log"
    if (Test-Path $лог) { Remove-Item $лог -Force }

    # «/S app1\garazh-cp» — ключ и значение, кавычить целиком нельзя.
    $частиБазы = $База.Trim() -split '\s+', 2

    $общие = @(
        "DESIGNER"
        $частиБазы
        "/N", $Пользователь
        "/P", $Пароль
        "/DisableStartupDialogs"
        "/DisableStartupMessages"
        "/Out", $лог, "-NoTruncate"
    )

    $строкаАргументов = (($общие + $аргументы) | ForEach-Object { ВКавычки $_ }) -join " "

    $начало = Get-Date
    $процесс = Start-Process -FilePath $Платформа -ArgumentList $строкаАргументов -Wait -PassThru
    $секунды = [int]((Get-Date) - $начало).TotalSeconds

    $текст = ПрочитатьЛог $лог
    if ($текст) { Write-Host $текст }

    if ($процесс.ExitCode -ne 0) {
        Отказ "Шаг «$имяШага» завершился с кодом $($процесс.ExitCode). Лог: $лог"
    }

    if ($текст -match "(?im)^\s*(Ошибка|Помилка|Error)") {
        Отказ "Шаг «$имяШага» вернул код 0, но в логе есть ошибка (см. выше). Лог: $лог"
    }

    Write-Host "  готово за $секунды с" -ForegroundColor Green
}

# --- 1. Точка отката ---------------------------------------------------------
# Объединение меняет основную конфигурацию необратимо: «отменить» его нечем,
# кроме как загрузить обратно то, что было до.
if ($БезРезервнойКопии) {

    Шаг "Резервная копия пропущена (ключ -БезРезервнойКопии)"
    Write-Host "Откатывать объединение будет нечем." -ForegroundColor Yellow

} else {

    Шаг "Сохраняю текущую конфигурацию базы — точка отката"

    $папкаКопий = Join-Path $рабочийСтол "1c-до-объединения"
    if (-not (Test-Path $папкаКопий)) { New-Item -ItemType Directory -Path $папкаКопий | Out-Null }

    $копия = Join-Path $папкаКопий ("до-объединения-" + (Get-Date -Format "yyyy-MM-dd-HHmm") + ".cf")
    ЗапуститьКонфигуратор "backup" @("/DumpCfg", $копия)

    if (-not (Test-Path $копия)) { Отказ "Конфигуратор отработал, но резервная копия не появилась: $копия" }

    $размерКопии = [math]::Round((Get-Item $копия).Length / 1MB, 1)
    Write-Host "  $копия  ($размерКопии МБ)" -ForegroundColor Green
    Write-Host "  Откат, если объединение не понравится: /LoadCfg этого файла." -ForegroundColor DarkGray
}

# --- 2. Объединение ----------------------------------------------------------
Шаг "Объединяю конфигурацию с файлом"

$аргументыОбъединения = @("/MergeCfg", $Файл)
if ($Настройки)      { $аргументыОбъединения += @("-Settings", $Настройки) }
if ($Принудительно)  { $аргументыОбъединения += "-force" }

ЗапуститьКонфигуратор "merge" $аргументыОбъединения

# --- 3. Применение к базе ----------------------------------------------------
if ($ПрименитьКБазе) {

    # Нужен монопольный доступ: пользователи должны выйти из базы.
    Шаг "Обновляю конфигурацию базы данных"
    ЗапуститьКонфигуратор "update" @("/UpdateDBCfg")

    Write-Host ""
    Write-Host "ГОТОВО. Конфигурация объединена и применена к базе." -ForegroundColor Green

} else {

    Write-Host ""
    Write-Host "ГОТОВО. Объединение выполнено в ОСНОВНОЙ конфигурации, к базе оно ещё НЕ применено." -ForegroundColor Green
    Write-Host "Откройте Конфигуратор, посмотрите результат и нажмите «Обновить конфигурацию" -ForegroundColor Green
    Write-Host "базы данных» (F7) — либо перезапустите этот скрипт с ключом -ПрименитьКБазе." -ForegroundColor Green
}
